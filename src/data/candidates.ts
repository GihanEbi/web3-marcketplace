/* Small builders keep the per-candidate data readable while ids stay stable. */

const exp = (
  n: string,
  i: number,
  company: string,
  title: string,
  location: string,
  startDate: string,
  endDate: string | null,
  description: string,
): WorkExperience => ({ id: `exp-${n}-${i}`, company, title, location, startDate, endDate, description });

const edu = (
  n: string,
  i: number,
  school: string,
  degree: string,
  field: string,
  startYear: number,
  endYear: number | null,
): Education => ({ id: `edu-${n}-${i}`, school, degree, field, startYear, endYear });

const cert = (n: string, i: number, name: string, issuer: string, year: number): Certification => ({
  id: `cert-${n}-${i}`,
  name,
  issuer,
  year,
});

const proj = (
  n: string,
  i: number,
  title: string,
  description: string,
  url: string,
  tags: string[],
): PortfolioProject => ({ id: `port-${n}-${i}`, title, description, url, tags });

